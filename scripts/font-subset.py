#!/usr/bin/env python3
"""Builds the UI font: justfont 粉圓 (Open Huninn, SIL OFL 1.1) cut down to the characters the game actually uses,
split in two so the first load stays small:
    client/public/fonts/huninn-menu.woff2  what the main menu / settings / licence card / first-run screens show
                                           (scripts/font-menu-text.ts lists those sources); preloaded
    client/public/fonts/huninn-game.woff2  every other character (story, karens, HUD, stores…)
Both are one font family with disjoint `unicode-range`s, so the browser downloads the game file only when one of its
characters is shown (the menu also warms it up once it is idle). The @font-face block + preload in client/index.html
(between the font-subset markers) is generated here, with a content hash in the URLs.
Re-run after adding new text (no arguments needed):
    pip install fonttools brotli && python3 scripts/font-subset.py
The full font is downloaded once into .cache/ (not committed). Lists checked by tests/font.test.ts:
scripts/font-chars.txt (all non-ASCII characters) and scripts/font-menu-chars.txt (the menu file's)."""
import glob, hashlib, json, os, re, subprocess, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '.cache', 'jf-openhuninn-2.1.ttf')
URL = 'https://github.com/justfont/open-huninn-font/releases/download/v2.1/jf-openhuninn-2.1.ttf'
FONTS = os.path.join(ROOT, 'client', 'public', 'fonts')
OUT_MENU = os.path.join(FONTS, 'huninn-menu.woff2')
OUT_GAME = os.path.join(FONTS, 'huninn-game.woff2')
OLD = os.path.join(FONTS, 'huninn.woff2')  # single-file font before round 27
HTML = os.path.join(ROOT, 'client', 'index.html')
LIST = os.path.join(ROOT, 'scripts', 'font-chars.txt')  # checked by tests/font.test.ts
MENU_LIST = os.path.join(ROOT, 'scripts', 'font-menu-chars.txt')
BEGIN, END = '<!-- font-subset:begin (generated by scripts/font-subset.py) -->', '<!-- font-subset:end -->'
BASE = set(chr(c) for c in range(0x20, 0x7f)) | set('，。、；：？！「」『』（）《》〈〉…—～・．％＋－×÷＝／＄★☆→←↑↓　')


def skip(ch):
    """Emoji / pictographs (system emoji font) and joiners are never taken from Huninn. Same rule as tests/font.test.ts."""
    c = ord(ch)
    return c <= 0x7f or 0x1F000 <= c <= 0x1FFFF or 0x2600 <= c <= 0x27BF or ch in '️‍'


def text_chars(text):
    return set(ch for ch in text if not skip(ch))


def used_chars():
    files = glob.glob(os.path.join(ROOT, 'client', 'src', '**', '*.ts'), recursive=True) + \
        glob.glob(os.path.join(ROOT, 'shared', '**', '*.ts'), recursive=True) + [HTML]
    chars = set(BASE)
    for f in files:
        with open(f, encoding='utf-8') as fh:
            chars |= text_chars(fh.read())
    return chars


def menu_chars():
    """Characters for the first-load file. Uses scripts/font-menu-text.ts (node + tsx); if that can't run, falls back
    to a rough static list (the font still covers everything, the menu may just pull in the game file too)."""
    try:
        out = subprocess.run(['node', '--import', 'tsx', os.path.join('scripts', 'font-menu-text.ts')], cwd=ROOT,
                             capture_output=True, text=True, timeout=120, check=True).stdout
        data = json.loads(out)
        for m in data.get('missing', []):
            print(f'WARNING: font-menu-text.ts: {m} not found (renamed?) — update MENU_SOURCES', file=sys.stderr)
        text = ''.join(data['strings'])
    except Exception as e:  # noqa: BLE001 — never block a font rebuild on this
        print(f'WARNING: could not run scripts/font-menu-text.ts ({e}); using a rough menu character list', file=sys.stderr)
        text = ''
        for f in ('client/index.html', 'client/src/quotes.ts', 'client/src/ui.ts', 'client/src/main.ts'):
            try:
                with open(os.path.join(ROOT, f), encoding='utf-8') as fh: text += fh.read()
            except OSError: pass
    return set(BASE) | text_chars(text)


def unicode_ranges(mine, other):
    """Compact unicode-range for `mine`: runs of consecutive used code points (gaps with no character of `other`
    are bridged, since nothing there is drawn from either file)."""
    allc = sorted(ord(c) for c in mine | other)
    mine_cp = set(ord(c) for c in mine)
    runs, start, last = [], None, None
    for cp in allc:
        if cp in mine_cp:
            if start is None: start = cp
            last = cp
        elif start is not None:
            runs.append((start, last)); start = None
    if start is not None: runs.append((start, last))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in runs)


def build(font_src, chars, out, opts):
    from fontTools import subset
    font = subset.load_font(font_src, opts)
    s = subset.Subsetter(opts); s.populate(text=''.join(sorted(chars))); s.subset(font)
    subset.save_font(font, out, opts)
    with open(out, 'rb') as fh: return hashlib.sha256(fh.read()).hexdigest()[:10]


def write_html(menu_range, game_range, menu_hash, game_hash):
    menu_url, game_url = f'fonts/huninn-menu.woff2?v={menu_hash}', f'fonts/huninn-game.woff2?v={game_hash}'
    block = '\n'.join([
        BEGIN,
        '  <!-- UI font (Huninn) split in two — only the menu file is preloaded; the game file loads when one of its characters',
        '       is shown (unicode-range) or when the menu warms up the game. Re-run python3 scripts/font-subset.py after adding text. -->',
        f'  <link rel="preload" href="{menu_url}" as="font" type="font/woff2" crossorigin />',
        '  <style>',
        f'    @font-face {{ font-family: "Huninn"; src: url("{menu_url}") format("woff2"); font-display: swap; unicode-range: {menu_range}; }}',
        f'    @font-face {{ font-family: "Huninn"; src: url("{game_url}") format("woff2"); font-display: swap; unicode-range: {game_range}; }}',
        '  </style>',
        '  ' + END,
    ])
    with open(HTML, encoding='utf-8') as fh: html = fh.read()
    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r'[\s\S]*?' + re.escape(END), lambda _m: block, html, count=1)
    else:
        # first run: replace the old single-file preload + @font-face
        pre = re.compile(r'[ \t]*<link rel="preload" href="fonts/huninn\.woff2"[^>]*>\n')
        face = re.compile(r'[ \t]*@font-face \{ font-family: "Huninn";[^}]*\}\n')
        if not pre.search(html) or not face.search(html):
            sys.exit('client/index.html: font-subset markers (or the old Huninn @font-face) not found')
        html = face.sub('', html, count=1)
        html = pre.sub(lambda _m: '  ' + block + '\n', html, count=1)
    with open(HTML, 'w', encoding='utf-8') as fh: fh.write(html)


if __name__ == '__main__':
    if not os.path.exists(SRC):
        os.makedirs(os.path.dirname(SRC), exist_ok=True)
        urllib.request.urlretrieve(URL, SRC)
    from fontTools import subset
    # the generated block in index.html has no text of its own (only ASCII), so scanning it is stable
    chars = used_chars()
    menu = menu_chars() & chars | set(BASE)
    game = chars - menu
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.name_IDs = ['*']; opts.notdef_outline = True
    os.makedirs(FONTS, exist_ok=True)
    mh = build(SRC, menu, OUT_MENU, opts)
    gh = build(SRC, game or {'　'}, OUT_GAME, opts)
    write_html(unicode_ranges(menu, game), unicode_ranges(game, menu) or 'U+3000', mh, gh)
    if os.path.exists(OLD): os.remove(OLD)
    with open(LIST, 'w', encoding='utf-8') as fh: fh.write(''.join(sorted(c for c in chars if ord(c) > 0x7f)))
    with open(MENU_LIST, 'w', encoding='utf-8') as fh: fh.write(''.join(sorted(c for c in menu if ord(c) > 0x7f)))
    kb = lambda p: os.path.getsize(p) / 1024
    print(f'{len(chars)} characters: menu {len(menu)} -> {OUT_MENU} ({kb(OUT_MENU):.0f} KB), '
          f'game {len(game)} -> {OUT_GAME} ({kb(OUT_GAME):.0f} KB)')
